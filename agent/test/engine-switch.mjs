import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { parseSessionEnv } from '../src/engine-launcher.js';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'mcw-engine-'));
process.env.MCW_MAXCLAUDE_CFG = root;
const { setEngine, engineEnvironment, sessionEngine } = await import('../src/sessions.js');
try {
  const values = parseSessionEnv('MAXCLAUDE_WORKDIR=/tmp\nMAXCLAUDE_EXTRA_ARGS=--model opus\nCUSTOM=a=b c\n# ignored\n');
  assert.equal(values.CUSTOM, 'a=b c');
  const next = engineEnvironment(values, {engine:'codex',cwd:'/tmp',claudeSid:'claude-id',transcript:'/tmp/a b.jsonl'});
  assert.equal(next.CUSTOM, values.CUSTOM);
  assert.equal(next.MAXCLAUDE_RESUME_SID, 'claude-id');
  assert.match(next.MAXCLAUDE_HANDOFF_PROMPT, /Read only the end/);
  assert.equal(engineEnvironment(next, {engine:'claude',transcript:'/b'}).MAXCLAUDE_RESUME_SID,'claude-id');
  for (const engine of ['bad',null,undefined,'Codex']) await assert.rejects(setEngine({name:'example',engine}),/engine must be/);
  await assert.rejects(setEngine({name:'../unsafe',engine:'codex'}),/name must match/);
  assert.equal(sessionEngine('missing'),'claude');
  assert.deepEqual(await setEngine({name:'missing',engine:'claude'}),{name:'missing',engine:'claude',changed:false});
  assert(!fs.existsSync(path.join(root,'sessions','missing.env')));
  const directory = path.join(root,'sessions');
  fs.mkdirSync(path.join(directory,'example.launchers'),{recursive:true});
  fs.writeFileSync(path.join(directory,'example.launchers','123'),'');
  const file = path.join(directory,'example.env');
  fs.writeFileSync(file,'MAXCLAUDE_ENGINE=codex\nCUSTOM=a=b c\n');
  assert.equal(sessionEngine('example'),'codex');
  const launcher = new URL('../../bin/maxclaude-pane', import.meta.url).pathname;
  const event = {session_id:'11111111-1111-4111-8111-111111111111',transcript_path:'/tmp/codex transcript.jsonl'};
  const record = (pid, data=event) => spawnSync(launcher,['--record-codex',directory,pid],{input:JSON.stringify(data),encoding:'utf8'});
  assert.equal(record('123').status,0);
  let recorded = parseSessionEnv(fs.readFileSync(file,'utf8'));
  assert.equal(recorded.MAXCLAUDE_CODEX_SID,event.session_id);
  assert.equal(recorded.MAXCLAUDE_CODEX_TRANSCRIPT,event.transcript_path);
  assert.equal(recorded.CUSTOM,'a=b c');
  assert(!('MAXCLAUDE_LAUNCHER_PID' in recorded));
  assert.equal(fs.statSync(file).mode & 0o777,0o600);
  fs.renameSync(file,path.join(directory,'renamed.env'));
  fs.renameSync(path.join(directory,'example.launchers'),path.join(directory,'renamed.launchers'));
  fs.writeFileSync(file,'MAXCLAUDE_ENGINE=claude\n');
  assert.equal(record('123').status,0);
  assert.match(record('999').stderr,/Cannot identify/);
  assert.match(record('123',{session_id:'invalid'}).stderr,/did not supply/);
  console.log('Engine switch assertions passed');
} finally { fs.rmSync(root,{recursive:true,force:true}); }
